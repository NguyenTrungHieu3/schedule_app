// Parse scripts/data/n5-vocab-source.md (Markdown export of "Từ vựng N5 — 25 bài")
// into src/data/n5Vocab.ts. Re-run after editing the source file:
//   node scripts/parse-n5-vocab.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(__dirname, 'data/n5-vocab-source.md'), 'utf8');

const DASH = '—'; // term / meaning separator used throughout the source
// Leading Japanese run (kana/kanji/full-width punctuation/digits), optionally
// followed by one parenthetical, used to split arrow-derived items that have
// no "—" separator (e.g. "ベトナムじん（ベトナム人）Người Việt").
const JP_LEAD = /^([　-ヿ一-鿿０-９ー]+(?:[（(][^）)]*[）)])?)\s*(.*)$/u;

function splitTermMeaning(segment) {
  const idx = segment.indexOf(DASH);
  if (idx === -1) return null;
  const term = segment.slice(0, idx).trim();
  const meaning = segment.slice(idx + DASH.length).trim();
  if (!term || !meaning) return null;
  return { term, meaning };
}

function parseNoDashSegment(segment) {
  const m = segment.trim().match(JP_LEAD);
  if (!m) return null;
  const term = m[1].trim();
  let meaning = m[2].trim().replace(/^[（(]/, '').replace(/[）)]$/, '').trim();
  if (!term || !meaning) return null;
  return { term, meaning };
}

// ponytail: arrow-derived / slash-joined edge cases cover ~5% of lines; a
// malformed segment is simply dropped rather than chasing every format.
function parseItemLine(rawLine) {
  const line = rawLine.replace(/^\d+\.\s*/, '').trim();
  const [primary, ...extras] = line.split('→').map((s) => s.trim());
  const cards = [];

  const dashCount = (primary.match(new RegExp(DASH, 'g')) || []).length;
  const hasSlash = /\s[／/]\s/.test(primary);
  const primaryParts = dashCount >= 2 && hasSlash ? primary.split(/\s[／/]\s/) : [primary];
  for (const part of primaryParts) {
    const card = splitTermMeaning(part);
    if (card) cards.push(card);
  }

  const primaryTerm = cards[0]?.term;
  for (const extra of extras) {
    const parts = /\s[／/]\s/.test(extra) ? extra.split(/\s[／/]\s/) : [extra];
    for (const part of parts) {
      const card = splitTermMeaning(part) ?? parseNoDashSegment(part);
      if (!card) continue;
      // "こちら (cách nói lịch sự)" etc: the source gives a generic qualifier
      // instead of a real translation, which collides across ここ/そこ/あそこ/どこ.
      if (card.meaning.toLowerCase() === 'cách nói lịch sự' && primaryTerm) {
        card.meaning = `Cách nói lịch sự của ${primaryTerm}`;
      }
      cards.push(card);
    }
  }

  return cards;
}

const lessons = [];
let current = null;
for (const rawLine of src.split('\n')) {
  const lessonHeader = rawLine.match(/^##\s*Bài\s*(\d+)\s*—\s*(.+?)\s*$/);
  if (lessonHeader) {
    current = { id: Number(lessonHeader[1]), title: lessonHeader[2].trim(), words: [] };
    lessons.push(current);
    continue;
  }
  const itemLine = rawLine.match(/^\d+\.\s/);
  if (itemLine && current) {
    current.words.push(...parseItemLine(rawLine));
  }
}

const totalWords = lessons.reduce((n, l) => n + l.words.length, 0);
console.log(`Parsed ${lessons.length} lessons, ${totalWords} vocab cards.`);
for (const l of lessons) console.log(`  Bài ${l.id} — ${l.title}: ${l.words.length} từ`);

const out = `// Generated by scripts/parse-n5-vocab.mjs from scripts/data/n5-vocab-source.md.
// Re-run the script after editing the source file instead of hand-editing this file.

export interface VocabWord {
  term: string;
  meaning: string;
}

export interface VocabLesson {
  id: number;
  title: string;
  words: VocabWord[];
}

export const n5Lessons: VocabLesson[] = ${JSON.stringify(lessons, null, 2)};
`;

writeFileSync(join(__dirname, '../src/data/n5Vocab.ts'), out, 'utf8');
console.log('Wrote src/data/n5Vocab.ts');
